public class AssignmentOperators {
    public static void main(String[] args) {
        int a = 10; // assign value to variable through assignment operator

        // Compound Assignment Operator : a type of operator which assign the value to itself
        byte b = 10;
        b += 5;     // No typecaste needed
        short s = 20;
        s -= 5;     // No typecaste needed
        char c = 70;
        c -= 5;     // No typecaste needed

        System.out.println(a);
        System.out.println(s);
        System.out.println(b);
        System.out.println(c);


    }
}
