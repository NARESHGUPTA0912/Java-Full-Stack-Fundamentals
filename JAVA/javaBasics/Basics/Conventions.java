package javaBasics.Basics;

// class name in PascalCase Convention
public class Conventions {

    // variable name in camelCase Convention
    static int varName = 7;

    // method name also camelCase Convention
    public static void methodConvention(){
        System.out.println(varName);
    }

    public static void main(String[] args) {
        methodConvention();
    }
    
}
